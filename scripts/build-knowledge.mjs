import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Builds src/lib/knowledge-base.ts from the curated source catalog.
 * Each source becomes one document per supported language, so 40 sources
 * produce 120 localized, source-grounded documents.
 */
const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = join(here, "..", "data", "knowledge-sources.jsonl");
const VERIFICATION = join(here, "..", "data", "knowledge-verification.json");
const OUT = join(here, "..", "src", "lib", "knowledge-base.ts");

const TOPICS = {
  phishing: ["Mengenali phishing", "Recognizing phishing", "Reconocer el phishing"],
  gift_cards: ["Penipuan gift card", "Gift card scams", "Estafas con tarjetas regalo"],
  jobs: ["Penipuan lowongan kerja", "Job scams", "Estafas de empleo"],
  romance: ["Penipuan romansa", "Romance scams", "Estafas románticas"],
  texts: ["Penipuan lewat SMS", "Text message scams", "Estafas por mensaje de texto"],
  recovery: ["Langkah setelah tertipu", "Steps after a scam", "Pasos después de una estafa"],
  general: ["Panduan umum penipuan", "General scam guidance", "Guía general de estafas"],
  business: ["Penipuan terhadap usaha", "Business scams", "Estafas a empresas"],
  reporting: ["Melaporkan penipuan", "Reporting fraud", "Reportar fraudes"],
  benefits: ["Bantuan pemerintah", "Government benefits", "Beneficios públicos"],
  identity: ["Pencurian identitas", "Identity theft", "Robo de identidad"],
  banking: ["Keamanan rekening bank", "Bank account safety", "Seguridad bancaria"],
  healthcare: ["Layanan kesehatan", "Health services", "Servicios de salud"],
  postal: ["Penipuan lewat pos", "Postal scams", "Estafas postales"],
  accounts: ["Keamanan akun", "Account security", "Seguridad de cuentas"],
  seniors: ["Perlindungan lansia", "Protecting older adults", "Protección de personas mayores"],
  investment: ["Investasi dan kripto", "Investments and crypto", "Inversiones y cripto"],
  finance: ["Layanan keuangan", "Financial services", "Servicios financieros"],
  privacy: ["Data pribadi", "Personal data", "Datos personales"],
  taxes: ["Penipuan pajak", "Tax scams", "Estafas fiscales"],
  tech: ["Dukungan teknis palsu", "Fake tech support", "Soporte técnico falso"],
};

const raw = await readFile(SOURCES, "utf8");
const sources = raw.split("\n").filter(Boolean).map((line) => JSON.parse(line));
let verification = { results: {} };
try {
  verification = JSON.parse(await readFile(VERIFICATION, "utf8"));
} catch {
  // Build still works before the first verification run; docs stay unverified.
}

const docs = [];
for (const source of sources) {
  const labels = TOPICS[source.topic];
  if (!labels) throw new Error(`Unknown topic: ${source.topic}`);
  const check = verification.results?.[source.id];
  const verified = check?.ok === true;
  const languages = [
    ["id", 0],
    ["en", 1],
    ["es", 2],
  ];
  for (const [lang, index] of languages) {
    docs.push({
      id: `${source.id}-${lang.toUpperCase()}`,
      title: `${source.publisher}: ${labels[index]}`,
      source_url: check?.finalUrl ?? source.url,
      publisher: source.publisher,
      jurisdiction: source.jurisdiction,
      doc_type: source.doc_type,
      language: lang,
      categories: source.categories,
      claim: source.claims[lang],
      verified,
      verified_status: check?.status ?? null,
      verified_at: check?.checkedAt ?? null,
    });
  }
}

const header = `// Generated by scripts/build-knowledge.mjs. Do not edit by hand.\n// ${docs.length} documents from ${sources.length} verified sources.\n`;
const body = `import type { Language, ScamCategory } from "./types";\n\nexport interface KnowledgeDoc {\n  id: string;\n  title: string;\n  source_url: string;\n  publisher: string;\n  jurisdiction: "US" | "ID" | "AU" | "UK" | "EU" | "GLOBAL";\n  doc_type: "agency_guidance" | "platform_help" | "regulator_notice";\n  language: Language;\n  categories: ScamCategory[];\n  claim: string;\n  verified: boolean;\n  verified_status: number | null;\n  verified_at: string | null;\n}\n\nexport const KNOWLEDGE_DOCS: KnowledgeDoc[] = ${JSON.stringify(docs, null, 2)};\n`;

await writeFile(OUT, header + body, "utf8");

const verifiedDocs = docs.filter((doc) => doc.verified).length;
const byLanguage = Object.fromEntries(
  ["id", "en", "es"].map((lang) => [lang, docs.filter((doc) => doc.language === lang).length]),
);
console.log(
  `Wrote ${OUT}\n${docs.length} docs (${verifiedDocs} verified) from ${sources.length} sources`,
  byLanguage,
);
if (docs.length !== 120) throw new Error(`Expected 120 documents, got ${docs.length}`);
